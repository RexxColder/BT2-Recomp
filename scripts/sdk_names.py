#!/usr/bin/env python3
"""Identifies the Sony SDK functions of a stripped executable by signature and writes them out twice.

Usage: scripts/sdk_names.py [--analyzer PATH]

Runs PS2Recomp's ps2_analyzer (its signature pass uses the sce-symbol-scanner database: byte patterns of the
Sony libraries, SDK 1.6-3.x) and reads the `name@0xADDRESS` lists of the TOML it writes:

  config/symbols/sdk.txt   every identified function, as symbol_addrs lines (the decomp gets the names);
  port/sdk_stubs.toml      the `stubs` list for port/recomp.toml: functions the runtime replaces with its own
                           high-level emulation (SIF/RPC, file I/O, DMA, threads...). Without these a stripped
                           game spins forever in sceSifInitRpc waiting for an IOP that is not there.

Names already used by another symbol file are left out (the project's name wins). Re-run after the split
changes; both outputs are generated, do not edit them.
"""

import re
import subprocess
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gamecfg import ROOT, TARGETS  # noqa: E402

PAIR = re.compile(r'"(\w+)@0x([0-9A-Fa-f]+)"')


def section(text, key):
    m = re.search(rf"^{key} = \[(.*?)^\]", text, re.M | re.S)
    return PAIR.findall(m.group(1)) if m else []


def main():
    args = sys.argv[1:]
    analyzer = Path(args[args.index("--analyzer") + 1]) if "--analyzer" in args else \
        ROOT / "tools/PS2Recomp/out/build/ps2xAnalyzer/ps2_analyzer"
    elf = ROOT / TARGETS[0]["elf"]
    with tempfile.TemporaryDirectory() as tmp:
        out = Path(tmp) / "analyzer.toml"
        subprocess.run([str(analyzer), str(elf), str(out)], check=True, stdout=subprocess.DEVNULL)
        text = out.read_text()
    stubs = section(text, "stubs")
    entries = section(text, "entry_points")

    taken = {}
    for path in sorted((ROOT / "config").glob("symbol_addrs*.txt")) + sorted((ROOT / "config/symbols").glob("*.txt")):
        if path.name == "sdk.txt":
            continue
        for line in path.read_text().splitlines():
            m = re.match(r"(\w+) = 0x([0-9A-Fa-f]+);", line)
            if m and not re.fullmatch(r"func_[0-9A-F]+", m.group(1)):
                taken[m.group(1)] = int(m.group(2), 16)
    named_addrs = set(taken.values())

    lines = ["// Sony SDK functions identified by PS2Recomp's analyzer (sce-symbol-scanner signatures).",
             "// Generated by scripts/sdk_names.py; do not edit."]
    seen = set()
    for name, addr in sorted({(n, int(a, 16)) for n, a in stubs + entries}, key=lambda x: x[1]):
        if name in taken or name in seen or addr in named_addrs:
            continue
        seen.add(name)
        lines.append(f"{name} = 0x{addr:08X}; // type:func")
    (ROOT / "config/symbols/sdk.txt").write_text("\n".join(lines) + "\n")

    stub_lines = ["# Generated by scripts/sdk_names.py: SDK functions the PS2Recomp runtime implements itself.",
                  "stubs = ["] + [f'  "{n}@0x{int(a, 16):08X}",' for n, a in stubs] + ["]"]
    (ROOT / "port").mkdir(exist_ok=True)
    (ROOT / "port/sdk_stubs.toml").write_text("\n".join(stub_lines) + "\n")
    print(f"{len(seen)} names -> config/symbols/sdk.txt; {len(stubs)} runtime stubs -> port/sdk_stubs.toml")


if __name__ == "__main__":
    main()
