#!/usr/bin/env python3
"""Translates the whole executable to C++ with PS2Recomp, from the project's own split and names.

Usage: scripts/recomp.py [--no-run]

Steps (each one documented in ps2-decomp-kit/docs/PORT_METHOD.md):
  1. scripts/funcmap.py      -> port/funcmap.csv      function boundaries + names (needs `ninja` done once)
  2. port/sdk_stubs.toml     from scripts/sdk_names.py (run it first; the stubs bind SDK functions to the runtime)
  3. port/recomp.toml        written here: [general] + the stubs (+ port/recomp_extra.toml if present, for
                             hand-written stubs/skips of this game, and `unstub`: SDK functions to keep as
                             translated game code although the runtime has a stub for them)
  4. tools/PS2Recomp/out/build/ps2xRecomp/ps2_recomp port/recomp.toml  -> port/build/recomp/*.cpp
Then: cmake -S port -B port/build/native -G Ninja && ninja -C port/build/native
"""

import re
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from gamecfg import ROOT, TARGETS  # noqa: E402

RECOMP = ROOT / "tools/PS2Recomp/out/build/ps2xRecomp/ps2_recomp"


def toml_list(path, key):
    if not path.exists():
        return []
    m = re.search(rf"^{key} = \[(.*?)^\]", path.read_text(), re.M | re.S)
    return re.findall(r'"([^"]+)"', m.group(1)) if m else []


def main():
    # --keep-funcmap: reuse port/funcmap.csv as it is (the hybrid port's rebuilds must keep the same function
    # boundaries; funcmap.py reads the current asm/ split, which the decomp keeps changing).
    if "--keep-funcmap" not in sys.argv:
        subprocess.run([sys.executable, str(Path(__file__).parent / "funcmap.py")], check=True)
    # A game whose code also lives in an overlay loaded at a fixed address (BT2: DBZP.BIN) adds it here:
    # scripts/overlay.py appends its functions to the map and writes the combined ELF the recompiler reads.
    elf_in = TARGETS[0]["elf"]
    if (Path(__file__).parent / "overlay.py").exists():
        subprocess.run([sys.executable, str(Path(__file__).parent / "overlay.py")], check=True)
        elf_in = "port/build/combined.elf"
    extra = ROOT / "port/recomp_extra.toml"
    # `unstub` names SDK functions whose runtime stub would bypass real IOP modules the game loads (e.g. the
    # sceSdRemote client when the real SDRDRV/LIBSD run on the IOP emulator): their game code is translated.
    unstub = set(toml_list(extra, "unstub"))
    stubs = [s for s in toml_list(ROOT / "port/sdk_stubs.toml", "stubs") if s.split("@")[0] not in unstub]
    stubs += toml_list(extra, "stubs")
    if unstub:
        # ps2_recomp also stubs any function whose *name* matches a runtime stub: rename them in the map.
        fm = ROOT / "port/funcmap.csv"
        rows = fm.read_text().splitlines()
        fm.write_text("\n".join(("game_" + r) if r.split(",")[0] in unstub else r for r in rows) + "\n")
    skip = toml_list(extra, "skip")
    # Hybrid port: the native C functions (port/tools/gen_native.py) stay translated too; they replace the
    # translation in the runtime's function table (every jal goes through it), so changing the native set does
    # not change the recompiler's output (a full rebuild).
    q = lambda items: "[\n" + "".join(f'  "{s}",\n' for s in items) + "]"  # noqa: E731
    (ROOT / "port/recomp.toml").write_text(f"""# Generated by scripts/recomp.py; edit port/recomp_extra.toml instead.
[general]
input = "{elf_in}"
ghidra_output = "port/funcmap.csv"
output = "port/build/recomp/"
single_file_output = false
patch_syscalls = false
patch_cop0 = true
patch_cache = true
stubs = {q(stubs)}
skip = {q(skip)}
""")
    print(f"port/recomp.toml: {len(stubs)} stubs, {len(skip)} skipped")
    if "--no-run" in sys.argv:
        return
    if not RECOMP.exists():
        # Checked before the old output is removed (2026-10-11: a missing binary cost the generated sources).
        sys.exit(f"{RECOMP} not built: ninja -C {RECOMP.parents[1]} ps2_recomp")
    # Names change between runs (new symbols): stale files of the previous run would still be globbed by CMake.
    out = ROOT / "port/build/recomp"
    if out.exists():
        import shutil
        shutil.rmtree(out)
    log = ROOT / "port/recomp.log"
    with open(log, "w") as f:
        subprocess.run([str(RECOMP), "port/recomp.toml"], cwd=ROOT, check=True, stdout=f, stderr=subprocess.STDOUT)
    report = log.read_text()
    m = re.search(r"Functions processed: .*", report)
    print(m.group(0) if m else "see port/recomp.log")


if __name__ == "__main__":
    main()
