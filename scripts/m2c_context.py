#!/usr/bin/env python3
"""Builds scratch/m2c_ctx/ctx.h: the type context for m2c --context, from BT3-Decompiled's headers.

Usage: .venv/bin/python scripts/m2c_context.py [--bt3 ~/Proyectos/BT3-Decompiled] [--out scratch/m2c_ctx/ctx.h]

 1. every BT3 header (include/**/*.h) is preprocessed as one unit (ee-gcc -E, -DM2CTX so include_asm.h emits
    nothing, GNU attributes/asm/inline keywords removed by macro);
 2. the result is parsed with m2c's own pycparser (m2c_pycparser), so only what m2c accepts goes out:
    - typedefs, structs, unions, enums: all of them (m2c needs their definitions);
    - function prototypes and extern globals: only for names that BT2's symbol files (config/symbols/*.txt,
      config/symbol_addrs.txt) define, since the sweep's asm calls and reads BT2 names;
    - function bodies and global definitions are dropped (a context must not define storage);
 3. the basic typedefs (s8..f32) are dropped (m2c knows them; include/types.h defines them for the compiler).

The output has no #include and no macros, so it is valid for both m2c --context and the compiler.
"""

import argparse
import os
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT / ".venv/lib/python3.14/site-packages"))

from m2c_pycparser import c_ast as ca  # noqa: E402
from m2c_pycparser.c_generator import CGenerator  # noqa: E402
from m2c_pycparser.c_parser import CParser  # noqa: E402

CC = ROOT / "tools/ee-gcc2.96/bin/ee-gcc"
# GNU spellings pycparser rejects, made empty or plain. __attribute__ takes a parenthesised argument.
GNU_MACROS = ["-D__attribute__(x)=", "-D__asm__(...)=", "-D__asm(...)=", "-D__inline__=", "-D__inline=",
              "-D__extension__=", "-D__restrict=", "-D__restrict__=", "-D__volatile__=volatile"]
BASIC = {"s8", "u8", "s16", "u16", "s32", "u32", "s64", "u64", "f32"}


def bt2_names():
    names = set()
    files = sorted((ROOT / "config/symbols").glob("*.txt")) + [ROOT / "config/symbol_addrs.txt"]
    for f in files:
        for line in f.read_text().splitlines():
            m = re.match(r"\s*(\w+)\s*=\s*0x[0-9A-Fa-f]+", line)
            if m:
                names.add(m.group(1))
    return names


def preprocess(bt3):
    inc = bt3 / "include"
    headers = sorted(p.relative_to(inc) for p in inc.rglob("*.h"))
    unit = "\n".join(f'#include "{h.as_posix()}"' for h in headers) + "\n"
    src = ROOT / "scratch/m2c_ctx/umbrella.c"
    src.parent.mkdir(parents=True, exist_ok=True)
    src.write_text(unit)
    out = ROOT / "scratch/m2c_ctx/pp.c"
    r = subprocess.run([str(CC), "-E", "-P", "-DM2CTX", f"-I{inc}", *GNU_MACROS, str(src), "-o", str(out)],
                       capture_output=True, text=True)
    if r.returncode:
        sys.exit("preprocess failed:\n" + r.stderr)
    return out.read_text()


def name_of(decl):
    node = decl.type
    while not isinstance(node, ca.TypeDecl):
        node = node.type
    return node.declname


def build(bt3, no_basic):
    text = preprocess(bt3)
    ast = CParser().parse(text, filename="pp.c")
    names = bt2_names()
    gen = CGenerator()
    seen, out = set(), []
    for node in ast.ext:
        if isinstance(node, ca.Typedef):
            if no_basic and node.name in BASIC:
                continue
            if node.name in seen:
                continue
            seen.add(node.name)
            out.append(gen.visit(node) + ";")
        elif isinstance(node, ca.FuncDef):
            node = node.decl
        if isinstance(node, ca.Decl):
            if node.name is None:  # a bare struct/union/enum definition
                if isinstance(node.type, (ca.Struct, ca.Union, ca.Enum)):
                    out.append(gen.visit(node) + ";")
                continue
            if node.name not in names or node.name in seen:
                continue
            seen.add(node.name)
            if isinstance(node.type, ca.FuncDecl):
                node.storage = []
                node.init = None
                out.append(gen.visit(node) + ";")
            else:
                node.storage = ["extern"]
                node.init = None
                out.append(gen.visit(node) + ";")
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--bt3", type=Path, default=Path.home() / "Proyectos/BT3-Decompiled")
    ap.add_argument("--out", type=Path, default=ROOT / "scratch/m2c_ctx/ctx.h")
    ap.add_argument("--keep-basic", action="store_true",
                    help="keep the s8..f32 typedefs (they clash with include/types.h in the compiled C)")
    a = ap.parse_args()
    lines = build(a.bt3, not a.keep_basic)
    a.out.parent.mkdir(parents=True, exist_ok=True)
    a.out.write_text("/* generated by scripts/m2c_context.py from BT3-Decompiled/include; do not edit */\n"
                     + "\n".join(lines) + "\n")
    print(f"{a.out}: {len(lines)} declarations")


if __name__ == "__main__":
    main()
