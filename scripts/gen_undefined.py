#!/usr/bin/env python3
"""Generate build/undefined_syms_auto.txt from the assembled objects.

splat emits symbolic references to data/code addresses it discovered but does not
always list them as undefined; the linker needs them defined. Each such symbol
name encodes its address (D_0030C040 -> 0x30C040, func_6B1EC0 -> 0x6B1EC0).
"""
import re
import subprocess
import sys
from pathlib import Path

args = [x for x in sys.argv[1:] if not x.startswith("--")]
BUILD = Path(args[0] if args else "build")
OUT = Path(args[1] if len(args) > 1 else "build/undefined_syms_auto.txt")
sys.path.insert(0, str(Path(__file__).resolve().parent))
from gamecfg import BINUTILS  # noqa: E402

NM = BINUTILS + "nm"

objs = sorted(str(p) for p in BUILD.rglob("*.o"))
defined, undefined = set(), set()
if objs:
    out = subprocess.run([NM] + objs, capture_output=True, text=True).stdout
    for line in out.splitlines():
        parts = line.split()
        if not parts:
            continue
        if parts[0] == "U" and len(parts) >= 2:
            undefined.add(parts[1])
        elif len(parts) >= 3:
            defined.add(parts[-1])

# Names of the symbol files: one a C file references while the C at that address defines it under another
# name (splat's func_, or a second copy) is bound to its address, as the auto names below are.
ROOT = Path(__file__).resolve().parent.parent
named = {}
for path in sorted((ROOT / "config").glob("symbol_addrs*.txt")) + sorted((ROOT / "config/symbols").glob("*.txt")):
    for m in re.finditer(r"^(\w+) = 0x([0-9A-Fa-f]+);", path.read_text(), re.M):
        named.setdefault(m.group(1), int(m.group(2), 16))

defs = []
for name in sorted(undefined - defined):
    m = re.search(r"_([0-9A-Fa-f]{4,8})$", name)
    if name in named and not re.fullmatch(r"(D|func|jtbl)_[0-9A-Fa-f]{8}", name):
        defs.append(f"{name} = 0x{named[name]:08X};")
    elif m:
        defs.append(f"{name} = 0x{int(m.group(1), 16):08X};")

if "--provide" in sys.argv:
    # Not flattened: splat's own file defines most; these only fill in what no object defines.
    defs = [f"PROVIDE({d[:-1]});" for d in defs]
OUT.parent.mkdir(parents=True, exist_ok=True)
OUT.write_text("/* generated by tools/gen_undefined.py */\n" + "\n".join(defs) + "\n")
print(f"{len(defs)} undefined symbols -> {OUT}")
