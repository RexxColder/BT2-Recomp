#!/usr/bin/env python3
"""Extracts the executables from the disc image, splits them with splat and writes build.ninja.

Usage: .venv/bin/python configure.py && ninja

Everything game-specific comes from game.toml (see gamecfg.py). This is BT3-Decompiled's configure.py with its
constants moved there, plus per-file compiler selection (config/cc_<key>.txt) and the flattened-ELF mode
RE Outbreak needed (tools: order_ld.py, gen_undefined.py).
"""

import os
import re
import shlex
import subprocess
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(0, str(Path(__file__).resolve().parent / "scripts"))
from gamecfg import (ROOT, GAME, BINUTILS, LINKER, CC, CC_FLAGS, CXX_FLAGS, ALT_CC, STRIP_PAD, AS_FLAGS, CC_AS_FLAGS,  # noqa: E402
                     TARGETS, SUBDIRS, alt_cc_files, gflag, as_gflag, rom_size)

ISO = ROOT / GAME["iso"]
DISC = ROOT / "disc"
SCRIPTS = "scripts"


def run(cmd, **kwargs):
    print("$", " ".join(shlex.quote(str(c)) for c in cmd))
    subprocess.run(cmd, check=True, cwd=ROOT, **kwargs)


def extract():
    if all((ROOT / t["original"]).exists() or (ROOT / t.get("elf", "-")).exists() for t in TARGETS):
        return
    if not ISO.exists():
        sys.exit(f"missing disc image: {ISO.name}")
    run(["7z", "x", "-y", f"-o{DISC}", ISO, *GAME["extract"]], stdout=subprocess.DEVNULL)


def make_rom(target):
    """An ELF target becomes the flat image of its LOAD segment (`rom_size` bytes, by default its filesz)."""
    if "elf" not in target:
        return
    size = rom_size(target)
    run([BINUTILS + "objcopy", "-O", "binary", "--gap-fill=0x00", f"--pad-to={target['image'][0] + size:#x}",
         ROOT / target["elf"], ROOT / target["original"]])
    # objcopy pads to the highest allocatable vaddr; the initialised image ends after rom_size bytes.
    with open(ROOT / target["original"], "r+b") as f:
        f.truncate(size)


def split(target):
    # splat shells out to mips-linux-gnu-* binutils; tools/bin aliases them.
    env = dict(os.environ, PATH=f"{ROOT / 'tools' / 'bin'}{os.pathsep}{os.environ['PATH']}")
    run([sys.executable, "-m", "splat", "split", ROOT / target["yaml"]], env=env,
        stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    if target["flatten"]:
        # One flattened section (no .text/.data boundaries): place every object in address order.
        run([sys.executable, ROOT / SCRIPTS / "order_ld.py", ROOT / f"build/{target['name']}.ld",
             ROOT / target["yaml"]])


def linked_c_files(yaml_path):
    """C/C++ files named by `c`/`cpp` subsegments in a splat yaml: the ones the linker script uses."""
    text = (ROOT / yaml_path).read_text()
    out = set()
    for kind, name in re.findall(r"\[0x[0-9A-Fa-f]+, (c|cpp), \"?([\w/]+)\"?\]", text):
        out.add(Path("src") / f"{name}.{kind}")
    return out


def write_extern_syms(target):
    """Linker script defining the listed symbols that lie outside the target's image."""
    text = (ROOT / target["yaml"]).read_text()
    lo, hi = target["image"]
    seen, inside = {}, {}
    for name in re.findall(r"^\s+- (config/\S+\.txt)$", text, re.M):
        if "reloc" in name:
            continue
        for line in (ROOT / name).read_text().splitlines():
            m = re.match(r"(\w+) = 0x([0-9A-Fa-f]+);", line)
            if m and not lo <= int(m.group(2), 16) < hi:
                seen.setdefault(m.group(1), int(m.group(2), 16))
            elif m:
                inside.setdefault(m.group(1), int(m.group(2), 16))
    out = ["/* Generated by configure.py: listed symbols outside this image. */"]
    out += [f"{name} = 0x{addr:08X};" for name, addr in sorted(seen.items(), key=lambda x: (x[1], x[0]))]
    # Inside it, a listed name some C file uses while the C at that address defines it under another name (splat's
    # func_XXXXXXXX of a leaf sweep, a second copy): bound to its address only when nothing defines it.
    out += [f"PROVIDE({name} = 0x{addr:08X});" for name, addr in sorted(inside.items(), key=lambda x: (x[1], x[0]))
            if name not in seen]
    (ROOT / target["extern_syms"]).write_text("\n".join(out) + "\n")


def sources(top, suffixes, subdir):
    """Files under top/ belonging to a target: its own subdir, or everything outside all subdirs."""
    found = []
    for path in sorted(p for s in suffixes for p in (ROOT / top).rglob(f"*{s}")):
        rel = path.relative_to(ROOT)
        # asm/**/nonmatchings holds per-function files pulled in by INCLUDE_ASM, not standalone units.
        if "nonmatchings" in rel.parts:
            continue
        owner = rel.parts[1] if len(rel.parts) > 1 and rel.parts[1] in SUBDIRS else None
        if owner == subdir:
            found.append(rel)
    return found


def write_ninja():
    out = [
        f"as = {BINUTILS}as",
        f"ld = {LINKER}",
        f"objcopy = {BINUTILS}objcopy",
        f"as_flags = {AS_FLAGS}",
        "",
        "rule as",
        "  command = $as $as_flags $in -o $out",
        "  description = AS $in",
        "",
        # ee-gcc's driver crashes when it runs its own assembler on a modern host, so compile
        # to assembly and assemble with the modern gas. gcc_prelude.inc makes `move` encode
        # as daddu, the way Sony's assembler did.
        "rule cc",
        f"  command = $cc $ccflags $gflag -S $in -o $out.s && $strip"
        f"$as {CC_AS_FLAGS} $asgflag include/gcc_prelude.inc $out.s -o $out && "
        f"{sys.executable} {SCRIPTS}/set_eabi64.py $out",
        "  description = CC $in",
        "",
        "rule ld",
        "  command = $ld -EL $scripts -Map $out.map -o $out",
        "  description = LD $out",
        "",
        "rule rom",
        "  command = $objcopy -O binary --gap-fill=0x00 $in $out $truncate",
        "  description = OBJCOPY $out",
        "",
        "rule check",
        "  command = cmp $in && touch $out",
        "  description = CHECK $in",
        "",
    ]
    alt = alt_cc_files()
    headers = " ".join(str(p.relative_to(ROOT)) for p in sorted((ROOT / "include").rglob("*.h")))
    for target in TARGETS:
        asm = sources("asm", [".s"], target["subdir"])
        # Only compile files that have a segment: work-in-progress files under src/ that are
        # not linked yet must not be able to break the build.
        linked = linked_c_files(target["yaml"])
        srcs = [p for p in sources("src", [".c", ".cpp"], target["src_subdir"]) if p in linked]
        objs = [Path("build") / p.with_suffix(".o") for p in asm + srcs]
        elf = target["elf_out"]
        ok = f"build/{target['name']}.ok"
        tag = target["name"].replace(".", "_")

        for src, obj in zip(asm, objs):
            out.append(f"build {obj}: as {src} | include/macro.inc include/labels.inc")
        for src, obj in zip(srcs, objs[len(asm):]):
            key = alt.get(str(src))
            out.append(f"build {obj}: cc {src} | {headers} include/gcc_prelude.inc")
            out.append(f"  cc = {ALT_CC[key] if key else CC}")
            out.append(f"  ccflags = {CXX_FLAGS if src.suffix == '.cpp' else CC_FLAGS}")
            out.append(f"  gflag = {gflag(src)}")
            out.append(f"  asgflag = {as_gflag(src)}")
            if key in STRIP_PAD:
                out.append(f"  strip = {sys.executable} {SCRIPTS}/strip_func_pad.py $out.s && ")
        if not target["flatten"]:
            # A C file can cover an address that asm (or another C file) still reaches by splat's label for it
            # (func_/D_XXXXXXXX: a leaf sweep's or a second copy's function, a transplant's data): those names
            # are bound to the address they spell when no object defines them.
            prov = f"build/{target['name']}_provide.ld"
            out += [
                f"rule provide_{tag}",
                f"  command = {sys.executable} {SCRIPTS}/gen_undefined.py --provide build $out",
                "  description = PROVIDE",
                "",
                f"build {prov}: provide_{tag} {' '.join(map(str, objs))}",
            ]
        if target["flatten"]:
            # splat does not list every address it referenced; define them from the assembled objects.
            out += [
                f"rule undef_{tag}",
                f"  command = {sys.executable} {SCRIPTS}/gen_undefined.py build {target['undef_syms']}",
                "  description = UNDEF",
                "",
                f"build {target['undef_syms']}: undef_{tag} {' '.join(map(str, objs))}",
            ]
        out += [
            f"build {elf}: ld | {' '.join(map(str, objs))} {' '.join(target['ld_scripts'])}",
            f"  scripts = {' '.join('-T ' + s for s in target['ld_scripts'])}",
            f"build {target['built']}: rom {elf}",
            # The linker rounds the segment up to its alignment; the original image ends at rom_size.
            f"  truncate = && truncate -s {rom_size(target)} {target['built']}" if "elf" in target else "",
            f"build {ok}: check {target['built']} {target['original']}",
            f"default {ok}",
            "",
        ]
    (ROOT / "build.ninja").write_text("\n".join(out))


def main():
    extract()
    for target in TARGETS:
        make_rom(target)
    (ROOT / "build").mkdir(exist_ok=True)
    for target in TARGETS:
        split(target)
        write_extern_syms(target)
        # splat only writes these when references are left undefined; the linker needs them present.
        for key in ("undef_funcs", "undef_syms"):
            p = ROOT / target[key]
            if not p.exists():
                p.write_text("")
    write_ninja()


if __name__ == "__main__":
    main()
