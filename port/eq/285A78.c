#include "common.h"

void *Dma_BeginDirect(void);
void Dma_EndDirect(void *a, s32 b, s64 c, s32 d);
void GfxPostQuad_Set(void *a, s32 b, s32 c, s32 d, s32 e, s32 f, s32 g, s32 h,
                     s32 i, s32 j, s32 k, s32 l);

void GfxPost_ShiftHighWord(s32 arg0, s32 arg1, s32 arg2) {
    u8 sp[0x80];
    u8 *b;
    u8 *p;
    s32 s0;
    s32 s1;
    s32 s3;
    s64 a2;

    b = Dma_BeginDirect();
    *(s64 *)(b + 0x00) = ((s64)0x10000000 << 32) | 0x800B;
    *(s64 *)(b + 0x08) = 0xE;
    *(s64 *)(b + 0x10) = ((s64)arg0 | 0x02080000) | ((s64)0xFFFC << 30);
    *(s64 *)(b + 0x18) = 0x4C;
    *(s64 *)(b + 0x20) = 0x30000;
    *(s64 *)(b + 0x28) = 0x47;
    *(s64 *)(b + 0x30) = ((s64)(arg2 - 1) << 48) | 0x01FF0000;
    *(s64 *)(b + 0x38) = 0x40;
    *(s64 *)(b + 0x40) = 0;
    *(s64 *)(b + 0x48) = 0x3F;
    *(s64 *)(b + 0x50) = (s64)0x8000 << 24;
    *(s64 *)(b + 0x58) = 0x3B;
    *(s64 *)(b + 0x60) = 0;
    *(s64 *)(b + 0x68) = 0x14;
    *(s64 *)(b + 0x70) = ((s64)arg1 | 0x2B220000) | ((s64)0xE800 << 20);
    *(s64 *)(b + 0x78) = 6;
    *(s64 *)(b + 0x80) = 0x116;
    *(s64 *)(b + 0x88) = 0;
    *(s64 *)(b + 0x90) = ((s64)0x3F800000 << 32) | 0x80808080;
    *(s64 *)(b + 0x98) = 1;
    *(s64 *)(b + 0xA0) = 0;
    *(s64 *)(b + 0xA8) = 0x4A;
    *(s64 *)(b + 0xB0) = ((s64)0x7208 << 32) | 0x7000;
    *(s64 *)(b + 0xB8) = 0x18;
    *(s64 *)(b + 0xC0) = ((s64)0x24000000 << 32) | 0x8040;
    *(s64 *)(b + 0xC8) = 0x53;

    p = b + 0xD0;
    s0 = 0;
    s1 = 0x3E;
    s3 = 8;
    do {
        s32 t3 = s3;
        s3 += 0x10;
        s1 -= 2;
        GfxPostQuad_Set(sp + 0x20, 0x700, 0x720, (s16)s0, 0, (s16)(s0 + 8), (s16)arg2, t3,
                        0, 8, arg2, 0);
        s0 += 0x10;
        *(s64 *)(p + 0x00) = (s64)*(s32 *)(sp + 0x40) | ((s64)*(s32 *)(sp + 0x44) << 16);
        *(s64 *)(p + 0x08) = (s64)*(s32 *)(sp + 0x30) | ((s64)*(s32 *)(sp + 0x34) << 16);
        *(s64 *)(p + 0x10) = (s64)*(s32 *)(sp + 0x48) | ((s64)*(s32 *)(sp + 0x4C) << 16);
        *(s64 *)(p + 0x18) = (s64)*(s32 *)(sp + 0x38) | ((s64)*(s32 *)(sp + 0x3C) << 16);
        p += 0x20;
    } while (s1 >= 0);

    *(s64 *)(b + 0x4D0) = ((s64)0x10000000 << 32) | 0x8002;
    *(s64 *)(b + 0x4D8) = 0xE;
    a2 = ((s64)0x01BF0000 << 32) | 0x01FF0000;
    *(s64 *)(b + 0x4E0) = a2;
    *(s64 *)(b + 0x4E8) = 0x40;
    *(s64 *)(b + 0x4F0) = ((s64)0x7200 << 32) | 0x7000;
    *(s64 *)(b + 0x4F8) = 0x18;
    Dma_EndDirect(b + 0x500, 0xE, a2, 0x40);
}
