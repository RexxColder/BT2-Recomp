#!/usr/bin/env python3
"""port/full/gs/shaders/* -> port/build/full/gen/shaders.h (SPIR-V for the Vulkan back end, GLSL text for GL),
the same arrays Tenkaichi3Decomp's port/tools/undefined.py writes (kGsVertSpv, kGsVertGlsl, ...)."""
import shutil, subprocess, sys
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "port/full/gs/shaders"
GEN = ROOT / "port/build/full/gen"
GEN.mkdir(parents=True, exist_ok=True)
arrays = []
for src in sorted(SRC.glob("*.*")):
    stage = src.suffix[1:]
    name = "k" + src.stem.capitalize() + stage.capitalize()
    spv = GEN / (src.name + ".spv")
    cmd = (["glslc", f"-fshader-stage={stage}", str(src), "-o", str(spv)] if shutil.which("glslc")
           else ["glslangValidator", "-V", "-S", stage, str(src), "-o", str(spv)])
    r = subprocess.run(cmd, capture_output=True, text=True)
    if r.returncode:
        sys.exit(f"shader {src.name}: {r.stdout[-300:]}{r.stderr[-300:]}")
    arrays.append(f"static const unsigned char {name}Spv[] = {{" + ",".join(map(str, spv.read_bytes())) + "};\n")
    if stage in ("vert", "frag"):   # GL back end: the GLSL text, NUL-terminated (as in BT3)
        data = src.read_bytes() + b"\0"
        arrays.append(f"static const unsigned char {name}Glsl[] = {{" + ",".join(map(str, data)) + "};\n")
(GEN / "shaders.h").write_text("/* generated by port/tools/gen_shaders.py */\n" + "".join(arrays))
print(f"{len(arrays)} arrays -> {GEN / 'shaders.h'}")
